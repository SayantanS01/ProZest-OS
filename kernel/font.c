static const uint8_t glyph_space[7] = {
    0, 0, 0, 0, 0, 0, 0
};

static const uint8_t glyph_unknown[7] = {
    0b01110, 0b10001, 0b00001, 0b00110,
    0b00100, 0b00000, 0b00100
};

const uint8_t *font_get_glyph(char character)
{
    if (character >= '0' && character <= '9') {
        return glyph_digits[character - '0'];
    }

    if (character >= 'A' && character <= 'Z') {
        return uppercase_glyphs[character - 'A'];
    }

    if (character >= 'a' && character <= 'z') {
        return lowercase_glyphs[character - 'a'];
    }

    if (character == ' ') {
        return glyph_space;
    }

    if ((character >= '!' && character <= '/') ||
        (character >= ':' && character <= '@') ||
        (character >= '[' && character <= '`') ||
        (character >= '{' && character <= '~')) {
        return punctuation_glyphs[character - ' '];
    }

    return glyph_unknown;
}
